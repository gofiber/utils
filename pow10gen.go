//go:build ignore

// pow10gen writes pow10tab.go: 10^e for e from pow10Min to pow10Max as a 128-bit
// mantissa with the top bit set, rounded down. Run it with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/big"
	"os"
)

const (
	pow10Min = -348
	pow10Max = 347
)

func main() {
	var out bytes.Buffer
	out.WriteString("// Code generated by pow10gen.go. DO NOT EDIT.\n\npackage utils\n\n")
	fmt.Fprintf(&out, "const (\n\tpow10Min = %d\n\tpow10Max = %d\n)\n\n", pow10Min, pow10Max)
	out.WriteString("// pow10Tab[e-pow10Min] is 10^e as a 128-bit mantissa with the top bit set, rounded down.\n")
	out.WriteString("var pow10Tab = [...]struct{ hi, lo uint64 }{\n")

	ten := big.NewInt(10)
	mask := new(big.Int).SetUint64(^uint64(0))
	for e := pow10Min; e <= pow10Max; e++ {
		var m *big.Int
		if e >= 0 {
			p := new(big.Int).Exp(ten, big.NewInt(int64(e)), nil)
			if n := p.BitLen(); n <= 128 {
				m = p.Lsh(p, uint(128-n))
			} else {
				m = p.Rsh(p, uint(n-128))
			}
		} else {
			// floor(2^(127+n) / 10^-e) has 128 bits, as 2^(n-1) < 10^-e < 2^n.
			d := new(big.Int).Exp(ten, big.NewInt(int64(-e)), nil)
			m = new(big.Int).Lsh(big.NewInt(1), uint(127+d.BitLen()))
			m.Quo(m, d)
		}
		hi := new(big.Int).Rsh(m, 64).Uint64()
		lo := new(big.Int).And(m, mask).Uint64()
		fmt.Fprintf(&out, "\t{%#016x, %#016x}, // 1e%d\n", hi, lo, e)
	}
	out.WriteString("}\n")

	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("pow10tab.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
